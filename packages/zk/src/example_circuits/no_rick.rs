/// The full circuit implementation.
///
/// In this struct we store the private input variables. We use `Option<F>` because
/// they won't have any value during key generation. During proving, if any of these
/// were `None` we would get an error.
#[derive(Debug)]
// #[cosmwasm_vm_derive::cosmwasm_circuit(i = 3)]

pub struct NoRickCircuit<F: PrimeField> {
    /// Fixed length of 20
    pub priv_input: Vec<Value<F>>,
}

impl<F: PrimeField> Default for NoRickCircuit<F> {
    fn default() -> Self {
        Self {
            priv_input: vec![Value::unknown(); 20],
        }
    }
}

impl<F: PrimeField> Circuit<F> for NoRickCircuit<F> {
    type Config = FieldConfig;
    type FloorPlanner = SimpleFloorPlanner;

    fn without_witnesses(&self) -> Self {
        Self::default()
    }

    fn configure(meta: &mut ConstraintSystem<F>) -> Self::Config {
        eprintln!("📋 NoRickCircuit::configure called - THIS SHOULD ALWAYS RUN");
        let advice = [meta.advice_column(), meta.advice_column()];
        let instance = meta.instance_column();
        let constant = meta.fixed_column();
        FieldChip::configure(meta, advice, instance, constant)
    }

    fn synthesize(
        &self,
        config: Self::Config,
        mut layouter: impl Layouter<F>,
    ) -> Result<(), Error> {
        let chip = FieldChip::<F>::construct(config);
        // --------------------------------------------------------------
        // 2️⃣ Powers of 256 (little‑endian) – they are plain F values,
        //    no gates are needed to load them.
        // this essentially moves between 8-bit byte values
        // --------------------------------------------------------------
        let _pow_256_0 = F::from(256u64.pow(0)); // 256⁰
        let pow_256_1 = F::from(256u64.pow(1)); // 256¹
        let pow_256_2 = F::from(256u64.pow(2)); // 256² = 65536
        let pow_256_3 = F::from(256u64.pow(3)); // 256³ = 16777216

        // Load all private inputs
        let mut chars = Vec::new();
        for (i, &char_val) in self.priv_input.iter().enumerate() {
            let char_cell =
                chip.load_private(layouter.namespace(|| format!("load char {}", i)), char_val)?;
            chars.push(char_cell);
        }

        // ---------------------------------------------------------------------
        // Load forbidden word from instance row 0 (only 1 instance column now)
        let rick_constant = chip.load_public(layouter.namespace(|| "load public rick"), 0)?;
        // Check for "rick" at every possible starting index (0 to 16)
        let mut conditions = Vec::new();
        for idx in 0..17 {
            let c0 = chars[idx].clone();
            let c1 = chars[idx + 1].clone();
            let c2 = chars[idx + 2].clone();
            let c3 = chars[idx + 3].clone();

            // Compute differences from 'r','i','c','k'
            let packed_val = c0.0.value().copied()
                + c1.0.value().copied() * Value::known(pow_256_1)
                + c2.0.value().copied() * Value::known(pow_256_2)
                + c3.0.value().copied() * Value::known(pow_256_3);

            // ---- compute the difference from the packed constant “rick” ----------
            // `rick_const` is a `Number<F>` that we loaded earlier.
            let diff_val = packed_val - rick_constant.0.value().copied();

            // ---- turn the difference into a private cell (so we can multiply it) --
            let diff =
                chip.load_private(layouter.namespace(|| format!("diff {}", idx)), diff_val)?;

            conditions.push(diff);
        }

        // Compute product of all conditions
        let mut product = conditions[0].clone();
        for i in 1..conditions.len() {
            product = chip.mul(
                layouter.namespace(|| format!("mul conditions {}", i)),
                product,
                conditions[i].clone(),
            )?;
        }

        // Compute inverse of product (fails if product is zero)
        let inv_p_val = product.0.value().map(|p| p.invert().unwrap_or(F::ZERO));
        let inv_p = chip.load_private(layouter.namespace(|| "load inv_p"), inv_p_val)?;

        // Multiply product by its inverse; should be 1 if no match
        let product_times_inv =
            chip.mul(layouter.namespace(|| "product times inv"), product, inv_p)?;

        // Load constant 1
        let one = chip.load_constant(layouter.namespace(|| "load one"), F::ONE)?;
        // Constrain product_times_inv to equal 1 by binding both to the same instance cell
        chip.constrain_equal(
            layouter.namespace(|| "enforce product_times_inv == 1"),
            &product_times_inv.0,
            &one.0,
        )?;

        Ok(())
    }
}

/// Public inputs to the Headstash Action circuit.
#[derive(Clone, Debug)]
pub struct NoRickInstance {
    /// word we are proving private value does not contain
    pub word: String,
}

impl NoRickInstance {
    /// serialize instances into set of circuit field [vesta::Scalar] with lenth `I`
    pub fn to_halo2_instance(&self) -> [[vesta::Scalar; 1]; 1] {
        let mut instance = [vesta::Scalar::zero(); 1];
        instance[0] = str_to_field(&self.word);
        [instance]
    }
    /// serialize instances into set of circuit field bytes with lenth `I`,specifically for cosmwasm-std api
    pub fn to_cosmwasm_instance(&self) -> Vec<u8> {
        let instances = self.to_halo2_instance();
        let mut bytes = Vec::with_capacity(1 * 32);
        for instance_row in instances.iter() {
            for scalar in instance_row.iter() {
                // to_repr() returns a 32-byte little-endian representation
                bytes.extend_from_slice(scalar.to_repr().as_ref());
            }
        }
        bytes
    }
}

/// The proving key for the Orchard Action circuit.
#[derive(Debug)]
pub struct ProvingKey {
    params: halo2_proofs::poly::commitment::Params<vesta::Affine>,
    pk: plonk::ProvingKey<vesta::Affine>,
}

impl ProvingKey {
    /// Builds existing proving key
    pub fn new(
        pk: plonk::ProvingKey<vesta::Affine>,
        params: halo2_proofs::poly::commitment::Params<vesta::Affine>,
    ) -> Self {
        ProvingKey { params, pk }
    }
    /// Builds new proving key.
    pub fn build() -> Self {
        let params = halo2_proofs::poly::commitment::Params::new(10);
        let circuit: NoRickCircuit<pasta_curves::Fp> = Default::default();

        let vk = plonk::keygen_vk(&params, &circuit).unwrap();
        let pk = plonk::keygen_pk(&params, vk, &circuit).unwrap();

        ProvingKey { params, pk }
    }

    /// Builds pk & vk, writes to file
    pub fn build_and_write(path: PathBuf) -> io::Result<()> {
        let mut writer = BufWriter::new(File::create(path)?);
        let pk = Self::build();
        pk.params.write(&mut writer)?;
        pk.pk.get_vk().write(&mut writer)?;
        writer.flush()
    }

    /// retrieve a clone of the params
    pub fn params(&self) -> halo2_proofs::poly::commitment::Params<vesta::Affine> {
        self.params.clone()
    }
}

